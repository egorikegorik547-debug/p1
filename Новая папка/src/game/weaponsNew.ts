  /* --- ствольная коробка: нижняя часть, крышка с рёбрами, цапфы --- */
  rrZ(g, oxide, 0.047, 0.056, 0.30, 0.008, 0, -0.008, 0);
  cylZ(g, oxideL, 0.0245, 0.0245, 0.29, 0, 0.0185, 0.005, 24);               // крышка ствольной коробки
  for (const x of [-0.011, 0, 0.011]) box(g, oxideL, 0.0035, 0.004, 0.25, x, x ? 0.0425 : 0.0452, 0.015, 0, 0, x * 3.2);   // рёбра жёсткости
  box(g, oxideL, 0.036, 0.034, 0.014, 0, 0.026, 0.158);                         // задняя крышка
  cylZ(g, steelL, 0.0042, 0.0042, 0.034, 0, 0.0265, 0.178, 8);                  // направляющая возвратной пружины
